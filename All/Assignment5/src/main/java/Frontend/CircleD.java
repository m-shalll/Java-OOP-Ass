    private void okButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_okButtonActionPerformed
        String radius=radiusI.getText();
        String x=xI.getText();
        String y=yI.getText();
        if(radius.isEmpty()||x.isEmpty()||y.isEmpty()){
            JOptionPane.showMessageDialog(new JFrame(), "Some fields are empty","Error",JOptionPane.ERROR_MESSAGE);
        }
        else{
             Map<String, Double> properties = new HashMap<>();
            properties.put("radius", Double.parseDouble(radius));
            properties.put("x", Double.parseDouble(x));
            properties.put("y", Double.parseDouble(y));
            Circle circle=new Circle();
            circle.setProperties(properties);
            Point point= new Point(Integer.parseInt(x),Integer.parseInt(y));
            circle.setPosition(point);
            this.createdCircle=circle;
            doClose(RET_OK);
            
        }
        
    }//GEN-LAST:event_okButtonActionPerformed

