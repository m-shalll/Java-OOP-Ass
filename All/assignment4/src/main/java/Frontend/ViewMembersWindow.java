    public void populateTable1(){
        TrainerRole trainer=new TrainerRole();
        ArrayList<Member> members=trainer.getListOfMembers();
        String columns[]={"ID","Name","Membership Type","Email","Phone number", "Status"};
        int size=members.size();
        String data[][] = new String[size][6];
        int i = 0; 
    for (Member member : members) {
        String line=member.lineRepresentation();
        String splitLine[]=line.split(",");
        data[i][0] = splitLine[0];           
        data[i][1] = splitLine[1];                          
        data[i][2] = splitLine[2];                         
        data[i][3] = splitLine[3];                    
        data[i][4] = splitLine[4]; 
        data[i][5] = splitLine[5];
        i++; 
    }
    DefaultTableModel model=new DefaultTableModel(data,columns);
    jTable1.setModel(model);
    }
